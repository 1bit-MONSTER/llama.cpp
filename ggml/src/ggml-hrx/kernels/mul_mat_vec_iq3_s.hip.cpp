// IQ3_S matvec kernel for the HRX0 backend.
//
// Mirrors mul_mat_vec_iq3_xxs.hip.cpp: one workgroup per (row, col) with
// 64 threads cooperating on a 256-weight super-block and 4 blocks in flight
// per workgroup. The IQ3_S block is 110 bytes
//   d(fp16) | qs[64] | qh[8] | signs[32] | scales[4]
// and decodes as: group g (32 weights) uses qs[8g..8g+7] as the low 8 bits of
// the 9-bit grid index, qh[g] supplies bit 8, signs[4g..4g+3] supply the sign
// bits (bits 0..3 for the even grid entry, 4..7 for the odd one), and
// scales[g/2] supplies a 4-bit multiplier (low nibble for even g, high for
// odd) as db = d * (1 + 2*nibble). Grid values are the true magnitudes (the
// 512-entry table stores 1,3,5,... so unlike IQ3_XXS there is no 1/4 factor).
#include <hip/hip_fp16.h>
#include <hip/hip_runtime.h>
#include <stdint.h>

struct hrx_block_iq3_s {
    unsigned short d;    // fp16 super-block scale
    uint8_t qs[64];      // 8 low grid-index bytes per 32-weight group
    uint8_t qh[8];       // bit 8 of the grid index per 32-weight group
    uint8_t signs[32];   // 4 sign bytes per 32-weight group
    uint8_t scales[4];   // 4-bit scale per 32-weight group
};

static_assert(sizeof(hrx_block_iq3_s) == 110, "wrong iq3_s block size");

